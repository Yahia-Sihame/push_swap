#include "ft_printf.h"

int	ft_print_str(const char *str)
{
	int	i;

	if (!str)
		return (write (1, "(null)", 6));
	i = 0;
	while (str[i])
	{
		write (2, &str[i], 1);
		i++;
	}
	return (i);
}
