#include "ft_printf.h"

int	ft_printf(const char *format, ...)
{
	va_list		args;
	int			count;
	int			i;

	va_start(args, format);
	count = 0;
	i = 0;
	while (format[i])
	{
		if (format[i] == '%' && format[i + 1])
		{
			i++;
			count += ft_check_args(&args, format[i]);
		}
		else
			count += ft_print_char(format[i]);
		i++;
	}
	va_end(args);
	return (count);
}
