#include "push_swap.h"

char	*ft_strchr(const char *str, int c)
{
	size_t			i;
	unsigned char	ch;

	if (!str)
		return (NULL);
	ch = (unsigned char)c;
	i = 0;
	while (str[i])
	{
		if ((unsigned char)str[i] == ch)
			return ((char *)(str + i));
		i++;
	}
	if (ch == '\0')
		return ((char *)(str + i));
	return (NULL);
}
