#include "../push_swap.h"

void	check_dup(int **ints)
{
	int	x;
	int	y;

	x = 0;
	while (ints[x])
	{
		y = x + 1;
		while (ints[y])
		{
			if (*ints[x] == *ints[y])
				free_exit(ints, NULL);
			y++;
		}
		x++;
	}
}
